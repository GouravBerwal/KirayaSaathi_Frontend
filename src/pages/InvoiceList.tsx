  const [newQrLabel, setNewQrLabel] = useState('');
  const [newQrPayeeName, setNewQrPayeeName] = useState('');
  const [newQrUpiId, setNewQrUpiId] = useState('');
  const [newQrImage, setNewQrImage] = useState<string | null>(null);

