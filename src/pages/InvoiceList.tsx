      const assignmentByTenant: Record<string, string> = {};
      assignments.forEach((assignment: TenantQrAssignmentApi) => {
        const tenantId = String(assignment.tenant_id);
        qrByTenant[tenantId] = String(assignment.qr_config);
        assignmentByTenant[tenantId] = String(assignment.id);
      });
      setTenantQrMap(qrByTenant);
      setTenantQrAssignmentIds(assignmentByTenant);
